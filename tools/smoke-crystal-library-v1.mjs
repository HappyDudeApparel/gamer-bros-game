import puppeteer from 'puppeteer-core';
const executablePath=process.env.CHROME;
if(!executablePath) throw new Error('CHROME path missing');
const browser=await puppeteer.launch({headless:true,executablePath,args:['--no-sandbox','--disable-dev-shm-usage','--use-gl=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage();
const fatalErrors=[];
const failedRequests=[];
page.on('pageerror',err=>fatalErrors.push('PAGE: '+err.message));
page.on('requestfailed',req=>{
  const u=req.url();
  if(/game\.js|three\.module|phase1\.css|styles\.css/i.test(u)) failedRequests.push(`${req.failure()?.errorText||'FAILED'} ${u}`);
});
await page.goto('http://127.0.0.1:8000/hybrid-v09/',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForFunction(()=>document.getElementById('boot')?.classList.contains('hidden')&&document.getElementById('ui')?.classList.contains('show'),{timeout:30000});
await new Promise(r=>setTimeout(r,1500));
const state=await page.evaluate(()=>({boot:document.getElementById('boot')?.className,ui:document.getElementById('ui')?.className,fatal:getComputedStyle(document.getElementById('fatal')).display,fatalText:document.getElementById('fatalText')?.textContent||'',canvas:document.querySelectorAll('canvas').length,title:document.title}));
console.log(JSON.stringify(state));
if(state.fatal!=='none') throw new Error('Fatal panel visible: '+state.fatalText);
if(state.canvas<1) throw new Error('No renderer canvas created');
if(fatalErrors.length) throw new Error(fatalErrors.join('\n'));
if(failedRequests.length) throw new Error('Required resource failed:\n'+failedRequests.join('\n'));
await browser.close();
